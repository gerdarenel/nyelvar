function PixelGlyph({ icon }: { icon: AwardIcon }) {
  const rows = GLYPHS[icon].trim().split("\n");
  const fills: Record<string, string> = { "1": "#1c140e", "2": "#f4e8d4", "3": "#9c4e2a", "4": "#4e6b3c", "5": "#c47a3a", "6": "#6a3a28", "7": "#8a5a32", "8": "#d7c4a2", "9": "#3d4a34" };
  return (
    <svg viewBox="0 0 16 16" shapeRendering="crispEdges" className="size-12" aria-hidden="true">
      {rows.flatMap((row, y) =>
        [...row].map((cell, x) =>
          fills[cell] ? <rect key={`${x}-${y}`} x={x} y={y} width="1" height="1" fill={fills[cell]} /> : null,
        ),
      )}
    </svg>
  );
}

export function Awards() {
  const books = useFolioStore((state) => state.books);
  const shelf = useFolioStore((state) => state.shelf);
  const awards = buildAwards(books, shelf);
  const [pane, setPane] = useState<"write" | "read">("write");
  const [open, setOpen] = useState<Award | null>(null);
  const visible = awards.filter((award) => award.kind === pane);

  return (
    <div
      className={cn(
        "relative h-full px-4 py-4 md:px-5",
        open ? "overflow-hidden" : "folio-scroll overflow-y-auto",
      )}
    >
      <div className="flex items-center justify-between gap-4">
        <div className="min-w-0">
          <h3 className="font-display text-xl font-semibold tracking-tight">Достижения</h3>
          <p className="mt-1 max-w-md text-sm leading-relaxed text-muted">
            Если бы я ждала совершенства, я бы никогда
            <br />
            не написала ни слова. (Маргарет Атвуд)
          </p>
        </div>
        <img
          src="/award-cat.png"
          alt=""
          className="h-28 w-auto shrink-0 object-contain"
        />
      </div>

      <div className="mt-5">
        <div className="flex items-end gap-1 px-3">
          <TabButton active={pane === "write"} onClick={() => setPane("write")}>
            писательские
          </TabButton>
          <TabButton active={pane === "read"} onClick={() => setPane("read")}>
            читательские
          </TabButton>
        </div>
        <section className={cn("bg-paper-deep/70 px-3 py-4", pane === "write" && "rounded-tl-none")}>
          <ul className="grid grid-cols-3 gap-2 sm:grid-cols-4 md:grid-cols-5">
            {visible.map((award) => (
              <li key={award.id}>
                <button
                  type="button"
                  onClick={() => setOpen(award)}
                  className={cn(
                    "flex h-full w-full flex-col items-center gap-1.5 px-1 py-2 text-center",
                    award.unlocked ? "opacity-100" : "opacity-35",
                  )}
                >
                  <span className="relative">
                    {award.image ? (
                      <img
                        src={award.image}
                        alt=""
                        loading="lazy"
                        decoding="async"
                        className="h-16 w-16 object-contain"
                      />
                    ) : (
                      <PixelGlyph icon={award.icon} />
                    )}
                    {award.count > 1 ? (
                      <span className="absolute -top-1 -right-1 flex h-5 min-w-5 items-center justify-center rounded-full bg-ink px-1 text-[10px] leading-none text-paper">
                        {award.count}
                      </span>
                    ) : null}
                  </span>
                </button>
              </li>
            ))}
          </ul>
        </section>
      </div>

      {open ? (
        <div
          className="absolute inset-0 z-20 flex items-center justify-center bg-ink/35 p-4"
          onClick={() => setOpen(null)}
          onWheel={(event) => event.preventDefault()}
        >
          <div
            role="dialog"
            aria-modal="true"
            aria-label={open.title}
            onClick={(event) => event.stopPropagation()}
            className="relative max-h-full w-full max-w-md overflow-y-auto bg-window p-5 shadow-[var(--shadow-window)]"
          >
            <button
              type="button"
              aria-label="Закрыть"
              onClick={() => setOpen(null)}
              className="absolute top-2 right-2 flex size-8 items-center justify-center text-muted hover:text-ink"
            >
              <X className="size-4" />
            </button>
            {open.unlocked ? (
              <div className="flex justify-center pt-2">
                <span className="relative">
                  {open.image ? (
                    <img
                      src={open.image}
                      alt=""
                      className="h-40 w-40 object-contain"
                    />
                  ) : (
                    <span className="block scale-[2.4] py-6">
                      <PixelGlyph icon={open.icon} />
                    </span>
                  )}
                  {open.count > 1 ? (
                    <span className="absolute -top-1 -right-1 flex h-6 min-w-6 items-center justify-center rounded-full bg-ink px-1 text-xs text-paper">
                      {open.count}
                    </span>
                  ) : null}
                </span>
              </div>
            ) : null}
            <p className={cn("text-center font-display text-lg font-semibold tracking-tight", open.unlocked ? "mt-4" : "mt-6")}>
              {open.title}
            </p>
            <p className="mt-3 text-sm leading-relaxed whitespace-pre-line">
              {open.unlocked ? open.message : "Пока закрыто. Кот ещё ждёт."}
            </p>
          </div>
        </div>
      ) : null}
    </div>
  );
}

function TabButton({
  active,
  onClick,
  children,
}: {
  active: boolean;
  onClick: () => void;
  children: string;
}) {
  return (
    <button
      type="button"
      onClick={onClick}
      className={cn(
        "h-8 px-3 text-sm",
        active ? "bg-paper-deep/70 text-ink" : "text-muted hover:text-ink",
      )}
    >
      {children}
    </button>
  );
}
